export const PETS: Pet[] = SEEDS.map(expand);

export const PET_BY_ID: Record<string, Pet> = Object.fromEntries(
  PETS.map((pet) => [pet.id, pet]),
);

export const FEATURED_PETS = PETS.filter((pet) => pet.featured);

export function getPet(id: string) {
  return PET_BY_ID[id];
}

export function searchPets(query: string, limit = 12): Pet[] {
  const q = query.trim().toLowerCase();
  if (!q) {
    return [...PETS]
      .sort((a, b) => {
        const tier = a.tier.localeCompare(b.tier);
        if (tier !== 0) return tier;
        return b.values.fr.points - a.values.fr.points;
      })
      .slice(0, limit);
  }
  const scored = PETS.map((pet) => {
    const name = pet.name.toLowerCase();
    const aliasHit = pet.aliases.some((alias) => alias.toLowerCase().includes(q));
    let score = 0;
    if (name === q) score = 100;
    else if (name.startsWith(q)) score = 80;
    else if (name.includes(q)) score = 60;
    else if (pet.aliases.some((alias) => alias.toLowerCase() === q)) score = 75;
    else if (aliasHit) score = 50;
    if (score > 0 && pet.liquidity === "high") score += 4;
    if (score > 0 && pet.featured) score += 2;
    return { pet, score };
  })
    .filter((row) => row.score > 0)
    .sort((a, b) => b.score - a.score || b.pet.values.fr.points - a.pet.values.fr.points);
  return scored.slice(0, limit).map((row) => row.pet);
}

export function variantsFor(pet: Pet): Variant[] {
  if (!pet.hasVariants) return ["regular"];
  return ["regular", "fly", "ride", "fr", "nfr", "mfr"];
}
