import type {
  Category,
  Glyph,
  Liquidity,
  Pet,
  Tier,
  Variant,
  VariantValue,
} from "./types";

interface Seed {
  id: string;
  name: string;
  aliases: string[];
  cat?: Category;
  tier: Tier;
  liq: Liquidity;
  demand: 1 | 2 | 3 | 4 | 5;
  featured?: boolean;
  frPts: number;
  frUsd: number;
  glyph: Glyph;
  nfrMul?: number;
  mfrMul?: number;
  noVariants?: boolean;
  pts?: Partial<Record<Variant, number>>;
  usd?: Partial<Record<Variant, number>>;
}

const MUL: Record<Variant, number> = {
  regular: 0.86,
  fly: 0.92,
  ride: 0.95,
  fr: 1,
  nfr: 2.45,
  mfr: 6.15,
};

function roundMoney(n: number) {
  if (n >= 100) return Math.round(n);
  if (n >= 20) return Math.round(n * 2) / 2;
  if (n >= 5) return Math.round(n * 10) / 10;
  return Math.round(n * 100) / 100;
}

function roundPts(n: number) {
  if (n >= 50) return Math.round(n);
  if (n >= 10) return Math.round(n * 2) / 2;
  return Math.round(n * 10) / 10;
}

function expand(seed: Seed): Pet {
  const hasVariants = !seed.noVariants && seed.cat !== "potion" && seed.cat !== "egg" && seed.cat !== "item";
  const values = {} as Record<Variant, VariantValue>;
  (Object.keys(MUL) as Variant[]).forEach((variant) => {
    let m = MUL[variant];
    if (variant === "nfr" && seed.nfrMul) m = seed.nfrMul;
    if (variant === "mfr" && seed.mfrMul) m = seed.mfrMul;
    if (!hasVariants) m = 1;
    values[variant] = {
      points: seed.pts?.[variant] ?? roundPts(seed.frPts * m),
      usd: seed.usd?.[variant] ?? roundMoney(seed.frUsd * m),
    };
  });
  return {
    id: seed.id,
    name: seed.name,
    aliases: seed.aliases,
    category: seed.cat ?? "pet",
    tier: seed.tier,
    liquidity: seed.liq,
    demand: seed.demand,
    featured: seed.featured,
    hasVariants,
    glyph: seed.glyph,
    values,
  };
}

